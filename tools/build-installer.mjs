// Builds simbook/INSTALL.SPK: one SPARK program that writes every SimBook file
// onto a SIM95 disk. Paste it into SPARK, save it, press F5.
//   node tools/build-installer.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "simbook/WEB");
const files = fs.readdirSync(src).sort();
const lit = (s) => '"' + s.replace(/"/g, '""') + '"';

let out = `' INSTALL.SPK - puts SimBook on this machine. Generated by tools/build-installer.mjs;
' edit the files in simbook/WEB and rebuild rather than editing this.
'
' Save this as C:\\MYFILES\\INSTALL.SPK in SPARK and press F5. SimBook becomes
' this machine's home page: its pages go into C:\\WEB, and the stock INDEX.HTM is
' moved aside to WELCOME.HTM, so the web server falls back to INDEX.ASP. It
' leaves C:\\BOOKDATA (accounts, posts) alone, so running it again upgrades
' SimBook without losing anybody. Then open http://YOURNAME/ in Voyager.

VAR t AS String
VAR NL AS String

SUB Main ()
    NL = Chr(10)
    IF NOT FS.Exists("C:\\WEB\\PICS") THEN FS.MakeDir("C:\\WEB\\PICS")
    MoveHomePage()
    Migrate()
${files.map((f, i) => `    File${i}()`).join("\n")}
    Print("SimBook is installed in C:\\WEB (${files.length} files).")
    Print("Open http://" + NET.HostName.Lower() + "/ in Voyager.")
END SUB

' HTTPD.SPK serves INDEX.ASP for a folder only when it has no INDEX.HTM, so the
' stock home page steps aside (to the first free name) instead of being deleted.
SUB MoveHomePage ()
    VAR names AS Array OF String
    VAR name AS String
    IF NOT FS.Exists("C:\\WEB\\INDEX.HTM") THEN RETURN
    names = ["WELCOME.HTM", "INDEX1.HTM", "INDEX2.HTM", "INDEX3.HTM", "INDEX4.HTM", "INDEX5.HTM", "INDEX6.HTM", "INDEX7.HTM", "INDEX8.HTM", "INDEX9.HTM"]
    FOR EACH name IN names
        IF NOT FS.Exists("C:\\WEB\\" + name) THEN
            FS.Rename("C:\\WEB\\INDEX.HTM", "C:\\WEB\\" + name)
            Print("  moved the old home page to C:\\WEB\\" + name)
            RETURN
        END IF
    NEXT
    THROW "C:\\WEB\\INDEX.HTM is in the way and there is nowhere to move it. Rename it yourself and run this again."
END SUB

SUB Put (name AS String)
    FS.Write("C:\\WEB\\" + name, t)
    Print("  wrote C:\\WEB\\" + name)
END SUB
`;
files.forEach((f, i) => {
  const lines = fs.readFileSync(path.join(src, f), "utf8").replace(/\r/g, "").split("\n");
  if (lines[lines.length - 1] === "") lines.pop();
  out += `\nSUB File${i} ()\n    t = ""\n`;
  for (const l of lines) out += `    t = t + ${lit(l)} + NL\n`;
  out += `    Put(${lit(f)})\nEND SUB\n`;
});
// Data from older versions is brought forward by MIGRATE.SPK, pasted in whole.
out += "\n" + fs.readFileSync(path.join(root, "simbook/MIGRATE.SPK"), "utf8");
fs.writeFileSync(path.join(root, "simbook/INSTALL.SPK"), out);
console.log(`simbook/INSTALL.SPK: ${files.length} files, ${out.length} bytes`);
