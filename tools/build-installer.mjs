// Builds simbook/INSTALL.SPK: one SPARK program that writes every SimBook file
// onto a SIM95 disk. Paste it into SPARK, save it, press F5.
//   node tools/build-installer.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "simbook/WEB/BOOK");
const files = fs.readdirSync(src).sort();
const lit = (s) => '"' + s.replace(/"/g, '""') + '"';

let out = `' INSTALL.SPK - puts SimBook on this machine. Generated by tools/build-installer.mjs;
' edit the files in simbook/WEB/BOOK and rebuild rather than editing this.
'
' Save this as C:\\MYFILES\\INSTALL.SPK in SPARK and press F5. It writes the
' pages to C:\\WEB\\BOOK and leaves C:\\BOOKDATA (accounts, posts) alone, so
' running it again upgrades SimBook without losing anybody.
' Then open http://YOURNAME/book/ in Voyager.

VAR t AS String
VAR NL AS String

SUB Main ()
    NL = Chr(10)
    IF NOT FS.Exists("C:\\WEB\\BOOK") THEN FS.MakeDir("C:\\WEB\\BOOK")
    IF NOT FS.Exists("C:\\WEB\\BOOK\\PICS") THEN FS.MakeDir("C:\\WEB\\BOOK\\PICS")
${files.map((f, i) => `    File${i}()`).join("\n")}
    Print("SimBook is installed in C:\\WEB\\BOOK (${files.length} files).")
    Print("Open http://" + NET.HostName.Lower() + "/book/ in Voyager.")
END SUB

SUB Put (name AS String)
    FS.Write("C:\\WEB\\BOOK\\" + name, t)
    Print("  wrote C:\\WEB\\BOOK\\" + name)
END SUB
`;
files.forEach((f, i) => {
  const lines = fs.readFileSync(path.join(src, f), "utf8").replace(/\r/g, "").split("\n");
  if (lines[lines.length - 1] === "") lines.pop();
  out += `\nSUB File${i} ()\n    t = ""\n`;
  for (const l of lines) out += `    t = t + ${lit(l)} + NL\n`;
  out += `    Put(${lit(f)})\nEND SUB\n`;
});
fs.writeFileSync(path.join(root, "simbook/INSTALL.SPK"), out);
console.log(`simbook/INSTALL.SPK: ${files.length} files, ${out.length} bytes`);
